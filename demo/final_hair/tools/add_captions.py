"""Burn timed captions (the narration, written for reading) into the demo video.

    python add_captions.py <in.mp4> <out.mp4> <work_dir>      (needs pillow; uses ffmpeg)

Each scene's caption lines share the scene's time in proportion to their word count.
"""
import os, subprocess, sys
from PIL import Image, ImageDraw, ImageFont

src, out, work = sys.argv[1:4]
os.makedirs(work, exist_ok=True)
SCENES = [
    (0, 10, ["XR gaze estimators need huge, exactly labelled eye datasets.",
             "Real capture is slow, costly and privacy-restricted, so we built a synthetic alternative in Blender."]),
    (10, 25, ["Our actual scene: a photoreal scanned head (3D Scan Store), rigged with left and right eye bones.",
              "Each eye rotates about its own centre.",
              "Fixation target 35 cm ahead of the eye midpoint; render camera locked at 40 cm."]),
    (25, 55, ["Everything is driven by our Python wrapper, run on the extracted release package.",
              "eyes.reset() looks at the centre.",
              "move(-1, 0): both pupils shift left.   move(1, 0): right.",
              "move(0, 1): up.   move(0, -1): down.   reset() returns exactly to centre.",
              "Each eyes.render() returns the input, both eye rotations and each pupil's pixel position (yellow cross)."]),
    (55, 75, ["The required sequence: ten frames, starting at the top and moving clockwise.",
              "Frame k uses θ = 2πk/10, with h = sin θ and v = cos θ.",
              "Both eyes converge on the moving target every time."]),
    (75, 90, ["Every render has a metadata record: frame, θ, the h and v inputs and world-frame rotations for both eyes,",
              "plus the 2D pupil centres as seen through the cornea, and the camera matrix."]),
    (90, 105, ["Pupil ground truth matches a lighting-free mask to within 0.39 px; all 19 API tests pass.",
               "Ten valid renders, metadata regenerated byte for byte: a deterministic, calibrated pipeline for synthetic gaze data."]),
]
W, H = 1920, 1080
font = None
for f in ("/System/Library/Fonts/Supplemental/Arial.ttf", "/System/Library/Fonts/Helvetica.ttc"):
    if os.path.exists(f):
        font = ImageFont.truetype(f, 34); break
font = font or ImageFont.load_default()

def wrap(text, maxw, d):
    words, lines, cur = text.split(), [], ""
    for w in words:
        t = (cur + " " + w).strip()
        if d.textlength(t, font=font) > maxw and cur:
            lines.append(cur); cur = w
        else:
            cur = t
    return lines + [cur]

caps = []
for t0, t1, lines in SCENES:
    words = [len(l.split()) for l in lines]; tot = sum(words); t = t0
    for l, n in zip(lines, words):
        dur = (t1 - t0) * n / tot
        caps.append((round(t + 0.1, 2), round(t + dur - 0.1, 2), l)); t += dur

inputs, filt, prev = ["-i", src], [], "0:v"
for i, (a, b, text) in enumerate(caps):
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0)); d = ImageDraw.Draw(img)
    ls = wrap(text, 1500, d); lh = 46; h = lh * len(ls) + 28
    y0 = H - 46 - h                      # bottom band, below every card's content
    wmax = max(d.textlength(l, font=font) for l in ls)
    d.rounded_rectangle(((W - wmax) / 2 - 24, y0, (W + wmax) / 2 + 24, y0 + h), radius=14, fill=(0, 0, 0, 185))
    for j, l in enumerate(ls):
        d.text(((W - d.textlength(l, font=font)) / 2, y0 + 14 + j * lh), l, font=font, fill=(255, 255, 255, 255))
    p = os.path.join(work, f"cap_{i:02d}.png"); img.save(p)
    inputs += ["-loop", "1", "-t", "105", "-i", p]
    filt.append(f"[{prev}][{i + 1}:v]overlay=0:0:enable='between(t,{a},{b})'[v{i}]"); prev = f"v{i}"
cmd = ["ffmpeg", "-y", "-loglevel", "error"] + inputs + ["-filter_complex", ";".join(filt), "-map", f"[{prev}]",
       "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", "-preset", "medium", "-movflags", "+faststart", out]
subprocess.run(cmd, check=True)
print("CAPTIONS", len(caps), "->", out)
