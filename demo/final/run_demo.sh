#!/usr/bin/env bash
# Phase 2H deterministic demo runner. Uses ONLY the release ZIP; never writes to it or to the repo's
# production files.
#
#   demo/phase2h/run_demo.sh [path/to/Techtonic.zip]
#
# Env: BLENDER (default: macOS app binary), PYTHON (needs numpy + pillow, for tools/verify.py).
# Output: demo/phase2h/work/  (recreated on every run), validation_results.txt, demo_assets/
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
zip="${1:-$here/../../dist/final/Techtonic.zip}"
B="${BLENDER:-/Applications/Blender.app/Contents/MacOS/Blender}"
PY="${PYTHON:-python3}"
EXPECT=6d0d8dd4e9a66d71773bee45b2fe142aa8879eadd9b0885720878870b64330e6
work="$here/work"; assets="$here/demo_assets"; res="$here/validation_results.txt"

got=$(shasum -a 256 "$zip" | cut -d' ' -f1)
[ "$got" = "$EXPECT" ] || { echo "ZIP SHA-256 mismatch: $got" >&2; exit 1; }
rm -rf "$work"; mkdir -p "$work" "$assets"
for d in pkg verify; do mkdir "$work/$d"; (cd "$work/$d" && unzip -q "$zip"); done
(cd "$work/pkg" && find . -type f -exec shasum -a 256 {} + | sort -k2) > "$work/pkg_before.sha"

{
echo "# Phase 2H validation results (generated by run_demo.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ))"
echo "# ZIP: $zip"
echo "# ZIP SHA-256: $got"
echo "# Blender: $("$B" --version | head -1)"
echo
echo "## ZIP root listing"; unzip -Z1 "$zip"
} > "$res"

echo "[1/5] wrapper calls + scene views (inside the extracted package)"
"$B" -b --factory-startup "$work/pkg/scene.blend" -P "$here/tools/demo_scene.py" -- "$work/pkg" "$work/demo" > "$work/demo_scene.log" 2>&1
grep -q DEMO_SCENE_DONE "$work/demo_scene.log"

echo "[2/5] five direction renders via the command line (for verify.py)"
for a in "--move -1 0" "--move 1 0" "--move 0 1" "--move 0 -1" "--reset"; do
  # shellcheck disable=SC2086
  "$B" -b --factory-startup "$work/verify/scene.blend" -P "$work/verify/wrapper/eyes.py" -- $a --out "$work/verify/directions" >> "$work/directions.log" 2>&1
done

echo "[3/5] regenerate the 10-frame clockwise sequence"
"$B" -b --factory-startup "$work/verify/scene.blend" -P "$work/verify/wrapper/eyes.py" -- --out "$work/sequence" > "$work/sequence.log" 2>&1

echo "[4/5] original evaluator verify.py + API test"
"$PY" "$here/tools/verify.py" "$work/verify" > "$work/verify.txt" 2>&1 || true
"$B" -b --factory-startup "$work/verify/scene.blend" -P "$here/tools/phase2g_api_test.py" -- "$work/verify" "$work/api" > "$work/api.log" 2>&1 || true

echo "[5/5] summarise"
(cd "$work/pkg" && find . -type f -exec shasum -a 256 {} + | sort -k2) > "$work/pkg_after.sha"
{
echo
echo "## Original evaluator (tools/verify.py, SHA-256 $(shasum -a 256 "$here/tools/verify.py" | cut -c1-16)…)"
echo "PASS lines: $(grep -c '^PASS' "$work/verify.txt")   FAIL lines: $(grep -c '^FAIL' "$work/verify.txt" || true)"
tail -1 "$work/verify.txt"
echo
echo "## API test (tools/phase2g_api_test.py)"
grep -E '^(PASS|FAIL)' "$work/api.log"; grep -E 'PASSED' "$work/api.log"
echo
echo "## Ten clockwise renders (packaged)"
"$PY" - "$work/verify/renders" <<'EOF'
import os, struct, sys
d = sys.argv[1]
for f in sorted(os.listdir(d)):
    w, h = struct.unpack(">II", open(os.path.join(d, f), "rb").read(24)[16:24])
    print(f"{f}  {w}x{h}  PNG")
EOF
echo
echo "## Metadata regeneration"
if cmp -s "$work/verify/metadata.json" "$work/sequence/metadata.json"; then echo "regenerated metadata.json is BYTE-IDENTICAL to the packaged metadata.json"; else echo "regenerated metadata.json DIFFERS from the packaged file"; fi
echo
echo "## Packaged files untouched by the demo run"
if cmp -s "$work/pkg_before.sha" "$work/pkg_after.sha"; then echo "all $(wc -l < "$work/pkg_before.sha" | tr -d ' ') extracted package files unchanged after the demo run"; else echo "PACKAGE FILES CHANGED"; fi
echo
echo "## Wrapper call log (verbatim, tools/demo_scene.py)"
cat "$work/demo/calls/call_log.txt"
} >> "$res"
cp "$work/demo/calls/"*.png "$work/demo/calls/"*.json "$work/demo/calls/call_log.txt" "$assets/" 2>/dev/null || true
mkdir -p "$assets/scene" "$assets/sequence"
cp "$work/demo/scene/"* "$assets/scene/"; cp "$work/verify/renders/"*.png "$assets/sequence/"; cp "$work/verify/metadata.json" "$assets/metadata.json"
echo "done: $res"
